fx_rgb_t fx_hsv8(uint8_t h, uint8_t s, uint8_t v)
{
    uint8_t region = h / 43;
    uint8_t rem = (uint8_t)((h - region * 43) * 6); /* 0..252 inside the region */
    uint8_t p = (uint8_t)(((uint16_t)v * (255 - s)) >> 8);
    uint8_t q = (uint8_t)(((uint16_t)v * (255 - ((uint16_t)((uint16_t)s * rem) >> 8))) >> 8);
    uint8_t t = (uint8_t)(((uint16_t)v * (255 - ((uint16_t)((uint16_t)s * (255 - rem)) >> 8))) >> 8);
    switch (region) {
    case 0: return (fx_rgb_t){ v, t, p };
    case 1: return (fx_rgb_t){ q, v, p };
    case 2: return (fx_rgb_t){ p, v, t };
    case 3: return (fx_rgb_t){ p, q, v };
    case 4: return (fx_rgb_t){ t, p, v };
    default: return (fx_rgb_t){ v, p, q };
    }
}

void fx_output_lut_build(uint8_t *lut, uint8_t brightness, uint8_t max_pct)
{
    for (int i = 0; i < 256; i++) {
        uint32_t v = ((uint32_t)k_fx_gamma[i] * brightness * max_pct + 12750u) / 25500u;
        lut[i] = (uint8_t)(v > 255u ? 255u : v);
    }
}
